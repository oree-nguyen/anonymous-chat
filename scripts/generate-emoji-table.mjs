import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const segmenter = new Intl.Segmenter('en', { granularity: 'grapheme' });
const emojiPresentation = /\p{Emoji_Presentation}/u;
const excluded = /[\u{1F3FB}-\u{1F3FF}\uFE0E\uFE0F\u200D]/u;
const candidates = [];

for (let point = 0x2000; point <= 0x1FAFF; point += 1) {
  if (point >= 0xD800 && point <= 0xDFFF) continue;
  const character = String.fromCodePoint(point);
  if (!emojiPresentation.test(character) || excluded.test(character)) continue;
  if ([...character].length !== 1) continue;
  if ([...segmenter.segment(character)].length !== 1) continue;
  candidates.push(character);
}

const size = 2 ** Math.floor(Math.log2(candidates.length));
if (size < 256) throw new Error(`Only ${candidates.length} safe emoji candidates were found.`);
const selected = candidates.slice(0, size);
const rows = [];
for (let index = 0; index < selected.length; index += 16) {
  rows.push(`  ${selected.slice(index, index + 16).map((item) => JSON.stringify(item)).join(', ')},`);
}
const output = `// Generated by scripts/generate-emoji-table.mjs. Do not edit manually.\nexport const EMOJI_TABLE = Object.freeze([\n${rows.join('\n')}\n]);\n`;
const here = dirname(fileURLToPath(import.meta.url));
await writeFile(resolve(here, '../crypto/emoji-table.js'), output, 'utf8');
console.log(`Generated ${selected.length} single-code-point emoji (${Math.log2(size)} bits per symbol).`);
